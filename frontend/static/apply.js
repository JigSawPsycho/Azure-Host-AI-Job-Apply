// Applications review UI — wires design markup to /api/applications endpoints.
(() => {
  "use strict";

  const els = {
    review: document.getElementById("review-area"),
    empty: document.getElementById("empty-state"),
    error: document.getElementById("error-state"),
    errorDetail: document.getElementById("error-detail"),
    counter: document.getElementById("counter"),
    progress: document.getElementById("progress-bar"),
    statusSummary: document.getElementById("status-summary"),
    badgeRow: document.getElementById("badge-row"),
    listingTitle: document.getElementById("listing-title"),
    listingMeta: document.getElementById("listing-meta"),
    cvSection: document.getElementById("cv-section"),
    cvName: document.getElementById("cv-name"),
    jobLink: document.getElementById("job-link"),
    letter: document.getElementById("letter"),
    charCount: document.getElementById("char-count"),
    genBy: document.getElementById("gen-by"),
    appliedStamp: document.getElementById("applied-stamp"),
    copy: document.getElementById("copy"),
    download: document.getElementById("download"),
    skip: document.getElementById("skip"),
    save: document.getElementById("save"),
    markSent: document.getElementById("mark-sent"),
    openListing: document.getElementById("open-listing"),
    prev: document.getElementById("prev"),
    next: document.getElementById("next"),
    status: document.getElementById("status"),
    printArea: document.getElementById("print-area"),
  };

  const SOURCE_LABELS = { au: "Seek AU", nz: "Seek NZ", wanted: "Wanted" };
  const state = { items: [], cursor: 0, detailCache: new Map() };

  function setStaticIcons() {
    els.prev.innerHTML = window.I.chevLeft(16);
    els.next.innerHTML = window.I.chevRight(16);
    els.copy.innerHTML = window.I.copy(12) + " Copy";
    els.download.innerHTML = window.I.download(12) + " PDF";
    els.skip.innerHTML = window.I.skip(13) + " Skip";
    els.save.innerHTML = window.I.check(13) + " Save edits";
    els.markSent.innerHTML = window.I.check(13) + " Mark sent";
    els.openListing.innerHTML = window.I.external(13) + " Open listing";
    els.genBy.innerHTML = window.I.sparkles(12) + " Generated by Claude · edits saved on the server";
  }

  function escapeHtml(s) {
    return String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  }

  function showStatus(message, kind) {
    els.status.textContent = message || "";
    els.status.style.color =
      kind === "err" ? "oklch(0.82 0.15 25)" : kind === "ok" ? "oklch(0.82 0.14 155)" : "var(--text-muted)";
    if (message) {
      clearTimeout(showStatus._timer);
      showStatus._timer = setTimeout(() => {
        els.status.textContent = "";
      }, 2500);
    }
  }

  function showErrorState(detail) {
    els.review.hidden = true;
    els.empty.hidden = true;
    els.error.hidden = false;
    els.errorDetail.textContent = detail || "";
  }

  async function fetchDetail(id) {
    if (state.detailCache.has(id)) return state.detailCache.get(id);
    const res = await fetch(`/api/applications/${id}`);
    if (!res.ok) throw new Error(`${res.status} ${res.statusText}`);
    const detail = await res.json();
    state.detailCache.set(id, detail);
    return detail;
  }

  async function render() {
    if (state.items.length === 0) {
      els.review.hidden = true;
      els.empty.hidden = false;
      return;
    }
    els.empty.hidden = true;
    els.review.hidden = false;

    const item = state.items[state.cursor];
    els.counter.textContent = `${state.cursor + 1} / ${state.items.length}`;
    els.progress.style.width = `${((state.cursor + 1) / state.items.length) * 100}%`;
    els.statusSummary.textContent = `${state.items.length} unsent`;

    els.appliedStamp.hidden = item.status !== "sent";

    const sourceLabel = SOURCE_LABELS[item.source] || "";
    els.badgeRow.innerHTML = sourceLabel
      ? `<span class="badge accent"><span class="dot"></span>${escapeHtml(sourceLabel)}</span>`
      : "";

    const title = [item.company, item.title].filter(Boolean).join(" — ") || `application ${item.id}`;
    els.listingTitle.textContent = title;

    const metaParts = [];
    if (item.company) metaParts.push(`<span>${escapeHtml(item.company)}</span>`);
    if (item.location) metaParts.push(`<span class="sep">·</span><span>${escapeHtml(item.location)}</span>`);
    els.listingMeta.innerHTML = metaParts.join("");

    if (item.recommended_cv) {
      els.cvSection.hidden = false;
      els.cvName.textContent = item.recommended_cv;
    } else {
      els.cvSection.hidden = true;
    }

    if (item.url) {
      els.jobLink.href = item.url;
      els.jobLink.innerHTML = window.I.external(12) + ` Open on ${escapeHtml(sourceLabel || "source")}`;
      els.jobLink.style.pointerEvents = "";
      els.openListing.href = item.url;
      els.openListing.style.pointerEvents = "";
    } else {
      els.jobLink.removeAttribute("href");
      els.jobLink.style.pointerEvents = "none";
      els.openListing.removeAttribute("href");
      els.openListing.style.pointerEvents = "none";
    }

    try {
      const detail = await fetchDetail(item.id);
      els.letter.value = detail.edited_body_md ?? detail.body_md ?? "";
      updateCharCount();
    } catch (err) {
      els.letter.value = "";
      showStatus("Could not load body: " + err.message, "err");
    }
  }

  function updateCharCount() {
    const v = els.letter.value || "";
    const words = v.split(/\s+/).filter(Boolean).length;
    els.charCount.textContent = `${v.length.toLocaleString()} chars · ~${Math.max(1, Math.ceil(words / 200))} min read`;
  }

  function advance(delta) {
    if (state.items.length === 0) return;
    state.cursor = (state.cursor + delta + state.items.length) % state.items.length;
    render();
  }

  async function save() {
    const item = state.items[state.cursor];
    if (!item) return;
    els.save.disabled = true;
    try {
      const res = await fetch(`/api/applications/${item.id}`, {
        method: "PATCH",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ edited_body_md: els.letter.value }),
      });
      if (!res.ok) throw new Error(`${res.status} ${res.statusText}`);
      const detail = await res.json();
      state.detailCache.set(item.id, detail);
      showStatus("Saved", "ok");
    } catch (err) {
      showStatus("Save failed: " + err.message, "err");
    } finally {
      els.save.disabled = false;
    }
  }

  async function markSent() {
    const item = state.items[state.cursor];
    if (!item) return;
    els.markSent.disabled = true;
    els.skip.disabled = true;
    try {
      await fetch(`/api/applications/${item.id}`, {
        method: "PATCH",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ edited_body_md: els.letter.value }),
      });
      const res = await fetch(`/api/applications/${item.id}/mark-sent`, { method: "POST" });
      if (!res.ok) throw new Error(`${res.status} ${res.statusText}`);
      state.items.splice(state.cursor, 1);
      if (state.cursor >= state.items.length) state.cursor = 0;
      render();
      window.refreshUnsentPill?.();
      showStatus("Marked sent", "ok");
    } catch (err) {
      showStatus("Mark sent failed: " + err.message, "err");
    } finally {
      els.markSent.disabled = false;
      els.skip.disabled = false;
    }
  }

  async function skip() {
    const item = state.items[state.cursor];
    if (!item) return;
    try {
      await fetch(`/api/applications/${item.id}/skip`, { method: "POST" });
      state.items.splice(state.cursor, 1);
      if (state.cursor >= state.items.length) state.cursor = 0;
      render();
      window.refreshUnsentPill?.();
    } catch (err) {
      showStatus("Skip failed: " + err.message, "err");
    }
  }

  async function copyText() {
    try {
      await navigator.clipboard.writeText(els.letter.value);
      showStatus("Copied", "ok");
    } catch {
      els.letter.focus();
      els.letter.select();
      showStatus("Select & copy manually", "err");
    }
  }

  function downloadPdf() {
    const item = state.items[state.cursor];
    if (!item) return;
    const header = [item.company, item.title].filter(Boolean).join(" — ");
    els.printArea.innerHTML = "";
    if (header) {
      const h = document.createElement("div");
      h.className = "print-header";
      h.textContent = header;
      els.printArea.appendChild(h);
    }
    const body = document.createElement("div");
    body.textContent = els.letter.value;
    els.printArea.appendChild(body);
    setTimeout(() => window.print(), 50);
  }

  function wire() {
    setStaticIcons();
    els.copy.addEventListener("click", copyText);
    els.download.addEventListener("click", downloadPdf);
    els.markSent.addEventListener("click", markSent);
    els.skip.addEventListener("click", skip);
    els.save.addEventListener("click", save);
    els.next.addEventListener("click", () => advance(1));
    els.prev.addEventListener("click", () => advance(-1));
    els.letter.addEventListener("input", updateCharCount);
  }

  async function init() {
    await new Promise((r) => setTimeout(r, 30));
    if (window.__aiApplyAnonymous) return;
    wire();
    try {
      const res = await fetch("/api/applications?status=unsent");
      if (!res.ok) throw new Error(`${res.status} ${res.statusText}`);
      state.items = await res.json();
    } catch (err) {
      showErrorState(err.message || String(err));
      return;
    }
    render();
  }

  init();
})();
